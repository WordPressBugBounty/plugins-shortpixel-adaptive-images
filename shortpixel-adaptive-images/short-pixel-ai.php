		define( 'SPAI_SNIP_VERSION', '3.1.0' );
		/** Version in the file names of the CDN-hosted vanilla JS bundles `spai-lib[-bg][-webp][-compat].<ver>.min.js`. */
		define( 'SHORTPIXEL_AI_VANILLAJS_VER', '1.1' );
		/** Absolute path of this file. */
		define( 'SHORTPIXEL_AI_PLUGIN_FILE', __FILE__ );
		/** Absolute path of the plugin directory, no trailing slash. */
		define( 'SHORTPIXEL_AI_PLUGIN_DIR', __DIR__ );
		/** `plugin_basename()` of the plugin directory, normally `shortpixel-adaptive-images` (the full path when the plugin lives outside WP_PLUGIN_DIR). Also names the OLD LQIP directory under uploads. */
		define( 'SHORTPIXEL_AI_PLUGIN_BASEDIR', plugin_basename( __DIR__ ) );
		/** `plugin_basename()` of this file, normally `shortpixel-adaptive-images/short-pixel-ai.php`. */
		define( 'SHORTPIXEL_AI_PLUGIN_BASENAME', plugin_basename( __FILE__ ) );
		/** URL of the plugin directory, `plugins_url(SHORTPIXEL_AI_PLUGIN_BASEDIR)`, no trailing slash. */
		define( 'SHORTPIXEL_AI_PLUGIN_BASEURL', plugins_url( SHORTPIXEL_AI_PLUGIN_BASEDIR ) );
		/** Parent directory of the plugin (normally `wp-content/plugins`); used to read other plugins' main files. */
		define( 'SHORTPIXEL_AI_WP_PLUGINS_DIR', dirname( __DIR__ ) );
		// Uploads base dir of the site that loads the plugin; `wp_upload_dir(null, false)` does not create the dated directory.
		$upDir = wp_upload_dir( null, false );
		/** Uploads base directory at load time (on multisite: of the current site; not updated by switch_to_blog()). Root of the LQIP cache `<uploads>/spai/lqip`. */
		define( 'SHORTPIXEL_AI_WP_UPLOADS_DIR', $upDir['basedir'] );

		// Shared ShortPixel modules
		// build/shortpixel/ is generated from the plugin-modules repository by `composer update`
		// (composer.json: namespace `ShortPixel\AI\`, hook prefix `shortpixel/ai/`, this plugin's text
		// domain). autoload.php registers the PSR-4 autoloader for them; nothing is loaded until used.
		require_once __DIR__ . '/build/shortpixel/autoload.php';

		// Controllers
		// Class declarations only, no side effects, except js-parser.class.php, which also loads the
		// bundled Minify/PathConverter/Psr\Cache libraries unless Minify is already declared.
		// simple-dom-parser.class.php declares the dead ShortPixelSimpleDomParser (never instantiated).
		// @todo Drop the simple-dom-parser.class.php require together with the dead class.
		require_once __DIR__ . '/includes/controllers/short-pixel-ai.class.php';
		require_once __DIR__ . '/includes/controllers/logger.class.php';
		require_once __DIR__ . '/includes/controllers/css-parser.class.php';

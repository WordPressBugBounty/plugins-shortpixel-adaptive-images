	/**
	 * Plugin bootstrap: constants, class loading, debug switch, lifecycle hooks, singleton boot.
	 *
	 * The plugin's own classes have no autoloader: every class file is required here on every
	 * request (front end, admin, AJAX, REST, cron, WP-CLI). The shared ShortPixel modules bundled
	 * in `build/shortpixel/` (generated by the build in `composer.json`) are autoloaded on first
	 * use through `build/shortpixel/autoload.php`. Nothing is hooked into the output yet; the
	 * `ShortPixelAI` singleton is created on `after_setup_theme` and registers its hooks in its
	 * constructor (HTML rewriting starts from `init` priority 1, `ShortPixelAI::init_ob()`).
	 *
	 * Everything runs only when `ShortPixelAI` is not declared yet, so a second copy of the plugin
	 * (or `uninstall.php` including this file after it was loaded) is a no-op. The file runs in
	 * the scope WordPress includes plugins from (global), so `$upDir` and `$spaiEnablePhpErrors`
	 * become global variables.
	 *
	 * Constants read but never defined here (define them in `wp-config.php`):
	 * - `DONOTCDN`: any value disables the rewriting for the request (`ShortPixelAI::isWelcome()`;
	 *   SPIO defines it on its own AJAX actions).
	 * - `SHORTPIXEL_AI_CLEANUP`: when the request is not rewritten, `init_ob()` buffers the output
	 *   through `ShortPixelAI::maybe_cleanup()` instead (turns CDN URLs of the `/http(s)://` form
	 *   back into origin URLs).
	 * - `SHORTPIXEL_AI_ORIG_NO_CDN`: `q_orig` URLs are not sent to the CDN (`get_api_url()` returns `''`).
	 * - `SPAI_FILENAME_RESOLUTION_UNSAFE`: disables the `-WxH` file-name size heuristic
	 *   (`ShortPixelUrlTools::get_image_size()`, `get_full_size_image_url()`).
	 * - `SPAI_ELEMENTOR_WORKAROUND`: enables a workaround for a list of Elementor widgets.
	 * - `SHORTPIXEL_NO_BANNER` (truthy): hides the banner on the settings page and the promo campaign
	 *   banner (`ShortPixelAI::setup_promo_banner()`), in every ShortPixel plugin that reads it.
	 *
	 * @package ShortPixel\AI
	 */

	!defined( 'ABSPATH' ) and exit;

    //ini_set('display_errors', 1); ini_set('display_startup_errors', 1); error_reporting(E_ALL);

	if ( !class_exists( 'ShortPixelAI' ) ) {
		/** Plugin version  used for asset versions, notices, feedback and the upgrade proposal. Keep in sync with the header. */

        //WP CLI
        // ShortPixelCLI (wp shortpixel ...) is declared only under WP-CLI.
        if(defined( 'WP_CLI' ) && WP_CLI) {
            require_once __DIR__ . '/includes/controllers/cli.class.php';
        }

		// Http
		// ShortPixel\AI\Request: thin wp_safe_remote_request() wrapper with JSON decoding.
		require_once __DIR__ . '/includes/http/request.php';

		/**
		 * Debug bootstrap, part 1: turns on PHP error display and the plugin's error handler.
		 *
		 * Acts only when `SHORTPIXEL_AI_DEBUG` is numeric (an int, or a numeric string from the
		 * query) and has the `ShortPixelAILogger::DEBUG_AREA_PHPERR` bit (2): sets `display_errors`
		 * and `display_startup_errors` to 1, `error_reporting(E_ALL)` and
		 * `set_error_handler(['ShortPixelAILogger', 'errorHandler'])` for the rest of the request.
		 * Must be called only once `SHORTPIXEL_AI_DEBUG` is defined.
		 *
		 * @var \Closure(): void $spaiEnablePhpErrors
		 */
		$spaiEnablePhpErrors = function() {
			if ( is_numeric( SHORTPIXEL_AI_DEBUG ) && ( SHORTPIXEL_AI_DEBUG & ShortPixelAILogger::DEBUG_AREA_PHPERR ) ) {
				ini_set( 'display_errors', 1 );
				ini_set( 'display_startup_errors', 1 );
				error_reporting( E_ALL );

				set_error_handler( [ 'ShortPixelAILogger', 'errorHandler' ] );
			}
		};

		//Debug comes from wp-config.php, or from the request for admins only. The user is known only after plugins load, hence plugins_loaded.
		// Debug bootstrap, part 2. SHORTPIXEL_AI_DEBUG is false or a bitmask of ShortPixelAILogger::DEBUG_*
		// (PHPERR 2, INCLUDE_CONTENT 4, CACHE 8, JSON 16, CSS 32, HTML 64 = LQIP 64); any truthy value logs to
		// the plugin log file. Resolution:
		// - defined in wp-config.php: kept; part 1 runs now;
		// - no ?SHORTPIXEL_AI_DEBUG= in the query: defined false now; part 1 runs (no-op);
		// - ?SHORTPIXEL_AI_DEBUG=<v> present and not defined in wp-config.php: the constant stays UNDEFINED
		//   until plugins_loaded priority 0, where it becomes <v> for users with manage_options (any
		//   scalar, also a non-numeric string) and false for everybody else, then part 1 runs. Any code
		//   reading the constant before that point throws "Undefined constant" on PHP 8.
		// - ?SHORTPIXEL_AI_DEBUG=delete: the constant becomes false; for manage_options users the log is
		//   cleared; the parameter is removed from $_GET.
		if ( !defined( 'SHORTPIXEL_AI_DEBUG' ) && !isset( $_GET[ 'SHORTPIXEL_AI_DEBUG' ] ) ) {
			/** Debug off: no wp-config.php value and no query parameter. */
			define( 'SHORTPIXEL_AI_DEBUG', false );
			//    : ShortPixelAILogger::DEBUG_INCLUDE_CONTENT | ShortPixelAILogger::DEBUG_AREA_HTML | ShortPixelAILogger::DEBUG_AREA_JSON | ShortPixelAILogger::DEBUG_AREA_CACHE | ShortPixelAILogger::DEBUG_AREA_CSS | ShortPixelAILogger::DEBUG_AREA_PHPERR);
		}

		if ( defined( 'SHORTPIXEL_AI_DEBUG' ) ) {
			$spaiEnablePhpErrors();
		}

		if ( isset( $_GET[ 'SHORTPIXEL_AI_DEBUG' ] ) ) {
			add_action( 'plugins_loaded', function() use ( $spaiEnablePhpErrors ) {
				$isAdmin    = current_user_can( 'manage_options' );
				$debugParam = is_scalar( $_GET[ 'SHORTPIXEL_AI_DEBUG' ] ) ? $_GET[ 'SHORTPIXEL_AI_DEBUG' ] : false;

				if ( !defined( 'SHORTPIXEL_AI_DEBUG' ) ) {
					/** Debug from the query: the parameter value for manage_options users (unless `delete`), else false. */
					define( 'SHORTPIXEL_AI_DEBUG', $isAdmin && $debugParam !== 'delete' ? $debugParam : false );
					$spaiEnablePhpErrors();
				}

				if ( $debugParam === 'delete' ) {
					$isAdmin && ShortPixelAILogger::instance()->clearLog();
					unset( $_GET[ 'SHORTPIXEL_AI_DEBUG' ] );
				}
			}, 0 );
		}
        /**
         * Stores the current Unix time in option `shortpixel_ai_installed_time`.
         *
         * Never hooked: nothing calls it. The installed time is written lazily by `Notice`
         * when the option is missing. Declared conditionally (inside the class_exists guard) in
         * the global namespace without a plugin prefix.
         *
         * @todo activatedTimeCollect() is dead; either call it from `ShortPixelAI::activate()` or remove it.
         *
         * @return void
         */
        function activatedTimeCollect(){
            update_option('shortpixel_ai_installed_time', time());
        }

		// Lifecycle. Activation: ShortPixelAI::activate() (re)schedules spai_account_check_event, runs
		// migrate_options(), sets the front-end test and on-boarding redirect flags and writes the
		// .htaccess CORS block when parse_css_files > 0. Deactivation: ShortPixelAI::deactivate() clears
		// the spai_account_check_event and spai_lqip_generate_event crons, the .htaccess block and the log;
		// it deletes no option. Uninstall is handled by uninstall.php (no register_uninstall_hook).
		// @todo The comment on the commented-out register_uninstall_hook line claims options are deleted on
		//       deactivate; deactivate deletes none and uninstall.php deletes only the LQIP state. Fix the
		//       comment (and decide on option cleanup in uninstall.php).
		register_activation_hook( __FILE__, [ 'ShortPixelAI', 'activate' ] );
		register_deactivation_hook( __FILE__, [ 'ShortPixelAI', 'deactivate' ] );
		//register_uninstall_hook( __FILE__, [ 'ShortPixelAI', 'uninstall' ] ); //Actually the options get deleted on deactivate.

		//init the singleton
		// ShortPixelAI::_() is created on after_setup_theme (default priority 10), so the active theme and
		// all plugins are loaded; its constructor registers every hook (output buffering from init prio 1).
        add_action( 'after_setup_theme', function() {
            ShortPixelAI::_();
        } );

    }
